-- ---------------------------------------------------------------------------
-- VIVORA Lab temporary Data API access policy.
-- ---------------------------------------------------------------------------
-- This is intentionally a Lab-only setup. Do not copy this GRANT/RLS strategy
-- to production.
--
-- Current Backend behavior:
-- - Creates Supabase clients with SUPABASE_ANON_KEY.
-- - Authenticates users with supabase.auth.getUser(access_token).
-- - Does not pass that user's JWT into table queries.
-- - Does not use a service_role key.
--
-- VIVORA Lab behavior:
-- - Application tables are explicitly kept with RLS disabled.
-- - anon/authenticated roles are explicitly granted the table permissions
--   needed by the current Backend because "Automatically expose new tables"
--   is OFF in this Supabase project.
--
-- Production direction:
-- - Move Backend-only writes to a server-only service role client, or
-- - Pass the authenticated user's JWT into Supabase table queries and replace
--   these broad Lab grants with proper per-user RLS policies.

grant usage on schema public to anon, authenticated;

