create table if not exists public.users (
  user_id bigint generated by default as identity primary key,
  id uuid unique references auth.users(id) on delete cascade,
  display_name text not null,
  email text unique,
  birthday date,
  age_visibility boolean not null default false,
  area text,
  icon_url text,
  profile text,
  bio text,
  is_private boolean not null default false,
  favorite_genres text[],
  role text not null default 'user'
    check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.tournaments (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'general',
  participants integer not null default 0,
  description text,
  rule text,
  start_at timestamptz,
  end_at timestamptz,
  created_by bigint references public.users(user_id) on delete set null,
  official boolean not null default false,
  image_url text,
  type text not null default 'score',
  evaluation_type text not null default 'objective'
    check (evaluation_type in ('objective', 'ai', 'human_vote')),
  target numeric,
  unit text,
  decimal_places integer not null default 0
    check (decimal_places between 0 and 6),
  direction text not null default 'highest'
    check (direction in ('highest', 'lowest', 'closest')),
  ai_criteria text,
  ai_score_min numeric not null default 0,
  ai_score_max numeric not null default 100,
  evaluation_provider text,
  evaluation_version text not null default 'v1',
  result_finalized_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_series (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  image_url text,
  category text not null default 'general',
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(user_id) on delete cascade,
  content text not null,
  image_url text,
  tags text[] not null default '{}',
  type text not null default 'commitment'
    check (type in ('commitment', 'challenge', 'tournament')),
  challenge_id bigint,
  tournament_id bigint references public.tournaments(id) on delete cascade,
  record numeric,
  verified boolean not null default false,
  media jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.post_likes (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id bigint not null references public.users(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(post_id, user_id)
);

create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id bigint not null references public.users(user_id) on delete cascade,
  content text not null check (char_length(content) <= 300),
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_participants (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  user_id bigint not null references public.users(user_id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.records (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  user_id bigint not null references public.users(user_id) on delete cascade,
  post_id bigint references public.posts(id) on delete set null,
  score numeric not null,
  unit text,
  verified boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.submission_evaluations (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  record_id bigint references public.records(id) on delete set null,
  user_id bigint not null references public.users(user_id) on delete cascade,
  evaluation_type text not null
    check (evaluation_type in ('objective', 'ai', 'human_vote')),
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'completed', 'failed')),
  provider text,
  version text not null default 'v1',
  score numeric,
  feedback text,
  criteria text,
  error_code text,
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  evaluated_at timestamptz,
  created_at timestamptz not null default now(),
  unique(post_id)
);

