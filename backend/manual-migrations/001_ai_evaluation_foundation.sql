    select 1
    from pg_constraint
    where conrelid = 'public.tournaments'::regclass
      and conname = 'tournaments_evaluation_type_check'
  ) then
    alter table public.tournaments
      add constraint tournaments_evaluation_type_check
      check (evaluation_type in ('objective', 'ai', 'human_vote'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.tournaments'::regclass
      and conname = 'tournaments_ai_score_bounds_check'
  ) then
    alter table public.tournaments
      add constraint tournaments_ai_score_bounds_check
      check (ai_score_min <= ai_score_max);
  end if;
end $$;

create table if not exists public.submission_evaluations (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  record_id bigint references public.records(id) on delete set null,
  user_id bigint not null references public.users(user_id) on delete cascade,
  evaluation_type text not null
    check (evaluation_type in ('objective', 'ai', 'human_vote')),
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'completed', 'failed')),
  provider text,
  version text not null default 'v1',
  score numeric,
  feedback text,
  criteria text,
  error_code text,
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  evaluated_at timestamptz,
  created_at timestamptz not null default now(),
  unique(post_id)
);

create index if not exists submission_evaluations_tournament_id_idx
