create table if not exists public.tournament_series (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  image_url text,
  category text not null default 'general',
  created_at timestamptz not null default now()
);

alter table public.tournaments
  add column if not exists series_id bigint references public.tournament_series(id) on delete set null;

alter table public.tournaments
  add column if not exists season_label text;

alter table public.tournaments
  add column if not exists publication_status text not null default 'published';

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.tournaments'::regclass
      and conname = 'tournaments_publication_status_check'
  ) then
    alter table public.tournaments
      add constraint tournaments_publication_status_check
      check (publication_status in ('draft', 'review', 'published', 'rejected'));
  end if;
end $$;

create index if not exists tournaments_series_id_idx
  on public.tournaments(series_id);

create table if not exists public.user_featured_titles (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(user_id) on delete cascade,
  user_title_id bigint not null references public.user_titles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id)
);

grant select, insert, update, delete on table public.tournament_series to anon, authenticated;
grant select, insert, update, delete on table public.user_featured_titles to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

alter table public.tournament_series disable row level security;
alter table public.user_featured_titles disable row level security;

